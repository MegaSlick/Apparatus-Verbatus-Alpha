"""Render the declared proof pages and write both declarations that describe them.

Run from the repository root:

    python3 proof/build_fixture.py

It writes three things and nothing else:

  proof/fixtures/<fixture-id>/page-N.png   the checked-in bytes themselves
  proof/fixtures.toml                      the ingress declaration the hook enforces
  proof/skeleton_fixture.toml              the pipeline's declaration of what is on them

**The checked-in bytes are the authority, not this script.** Spec 01 asks for fixed
checked-in bytes with expected digests precisely so that encoders, fonts and
metadata cannot vary across machines — and zlib's exact output, while a pure
function of its input for a given implementation, is not guaranteed identical
across zlib builds. So a machine whose regenerated bytes differ has not found a
defect in the fixture; it has found a different zlib. The test beside this script
asserts what actually matters and holds everywhere: the checked-in files decode to
exactly the pixels this generator describes.

Two declarations rather than one because they answer different questions and are
read by different things. `fixtures.toml` answers "may these bytes be in git?" and
is enforced by the ingress hook on every commit and push. `skeleton_fixture.toml`
answers "what is on these pages, and what should the fakes do?" and is read by the
stage programs as data.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from proof.synthetic_pages import (  # noqa: E402
    FIXTURE_ID,
    PAGES,
    crop_png,
    render_page,
)

PROOF_ROOT = Path(__file__).resolve().parent
FIXTURE_DIR = PROOF_ROOT / "fixtures" / FIXTURE_ID

# What the fake Perlector establishes for each act. Fixture-defined text proving
# structural wiring only: it says nothing whatever about reading ink, and the
# skeleton's report may not pretend otherwise.
ACTS = (
    {
        "key": "a1",
        "page_ordinal": 1,
        "proposal_ordinal": 0,
        "text": "SYNTHETIC ACT ONE alpha beta gamma",
    },
    {
        "key": "a2",
        "page_ordinal": 1,
        "proposal_ordinal": 1,
        "text": "SYNTHETIC ACT TWO delta epsilon zeta eta",
    },
)

# What each witness reports. Seat 1 agrees with the established reading, seat 2
# differs in one token and seat 3 stops short — so the recorded dissent is
# structural and non-trivial rather than uniformly empty. Dissent is not a
# quality signal (ARCHITECTURE, "On dissent"); it is here so the *shape* of the
# record is exercised.
TESTIMONY = {
    "a1": {
        "attestator_1": "SYNTHETIC ACT ONE alpha beta gamma",
        "attestator_2": "SYNTHETIC ACT ONE alpha beta gamna",
        "attestator_3": "SYNTHETIC ACT ONE alpha beta",
    },
    "a2": {
        "attestator_1": "SYNTHETIC ACT TWO delta epsilon zeta eta",
        "attestator_2": "SYNTHETIC ACT TWO delta epsilon zeta",
        "attestator_3": "SYNTHETIC ACT TWO delta epsiIon zeta eta",
    },
}

# The recovery region for the review scenario: an expanded recrop of act a1. It
# must stay inside the page and must not reach into act a2's bounds, or the
# recovery would be inventing an overlap rather than widening a crop.
RECOVERY_BOUNDS = {"a1": {"x": 16, "y": 16, "w": 168, "h": 88}}

WITNESS_SEATS = ("attestator_1", "attestator_2", "attestator_3")
WITNESS_FLOOR = 3


def page_descriptor(ordinal):
    for page in PAGES:
        if page["ordinal"] == ordinal:
            return page
    raise ValueError(f"no page {ordinal}")


def act_descriptor(page_ordinal, proposal_ordinal):
    for act in page_descriptor(page_ordinal)["acts"]:
        if act["ordinal"] == proposal_ordinal:
            return act
    raise ValueError(f"no act {proposal_ordinal} on page {page_ordinal}")


def render_all() -> dict[int, bytes]:
    return {page["ordinal"]: render_page(page) for page in PAGES}


def toml_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def build_ingress_manifest(rendered: dict[int, bytes]) -> str:
    lines = [
        "version = 1",
        "",
        "# A public-safe proof image is added as an exact [[fixture]] entry carrying:",
        "# path, sha256, bytes, media_type, source, and reason. The ingress check accepts",
        "# JPEG, PNG, and TIFF only when all six fields match the staged image exactly.",
        "",
        "# These are generated by proof/build_fixture.py from proof/synthetic_pages.py.",
        "# They contain no register material of any kind: they are abstract synthetic",
        "# marks, drawn by a few dozen lines of zlib and struct, and they are the only",
        "# input the walking skeleton has.",
    ]
    import hashlib

    for ordinal in sorted(rendered):
        data = rendered[ordinal]
        lines += [
            "",
            "[[fixture]]",
            f'path = "proof/fixtures/{FIXTURE_ID}/page-{ordinal}.png"',
            f'sha256 = "{hashlib.sha256(data).hexdigest()}"',
            f"bytes = {len(data)}",
            'media_type = "image/png"',
            f'source = "generated by proof/build_fixture.py, fixture {FIXTURE_ID}"',
            'reason = "synthetic walking-skeleton input; public-safe by construction"',
        ]
    return "\n".join(lines) + "\n"


def build_skeleton_fixture(rendered: dict[int, bytes]) -> str:
    import hashlib

    lines = [
        "# The pipeline's declaration of the synthetic fixture.",
        "#",
        "# Read as data by every stage program, never imported: stages exchange",
        "# artifacts on disk and import only common/, so a fixture that arrived as",
        "# Python would be a stage coupling itself to another package through a side",
        "# door. Generated by proof/build_fixture.py -- edit that, not this.",
        "",
        f"fixture_id = {toml_string(FIXTURE_ID)}",
        f"witness_seats = [{', '.join(toml_string(seat) for seat in WITNESS_SEATS)}]",
        f"witness_floor = {WITNESS_FLOOR}",
        "",
        "[adapter_recipes]",
        'door = "fake-door-v0"',
        'exemplar = "fake-exemplar-v0"',
        'designator = "fake-designator-v0"',
        'attestatores = "fake-attestatores-v0"',
        'perlector = "fake-perlector-v0"',
        'recensor = "fake-recensor-v0"',
        'archetypus = "fake-archetypus-v0"',
        'armarium = "fake-armarium-v0"',
    ]

    for ordinal in sorted(rendered):
        page = page_descriptor(ordinal)
        data = rendered[ordinal]
        lines += [
            "",
            "[[page]]",
            f"ordinal = {ordinal}",
            f'path = "fixtures/{FIXTURE_ID}/page-{ordinal}.png"',
            f'sha256 = "{hashlib.sha256(data).hexdigest()}"',
            f"width = {page['width']}",
            f"height = {page['height']}",
        ]

    for act in ACTS:
        source = act_descriptor(act["page_ordinal"], act["proposal_ordinal"])
        bounds = source["bounds"]
        lines += [
            "",
            "[[act]]",
            f"key = {toml_string(act['key'])}",
            f"page_ordinal = {act['page_ordinal']}",
            f"proposal_ordinal = {act['proposal_ordinal']}",
            f"x = {bounds['x']}",
            f"y = {bounds['y']}",
            f"w = {bounds['w']}",
            f"h = {bounds['h']}",
            f"text = {toml_string(act['text'])}",
        ]

    # One act runs across the page break. The continuation is a region of the
    # same act, not a third act: two acts, one cross-page continuation.
    continuation_source = act_descriptor(2, 1)
    lines += [
        "",
        "[[continuation]]",
        'act_key = "a2"',
        "page_ordinal = 2",
        f"x = {continuation_source['bounds']['x']}",
        f"y = {continuation_source['bounds']['y']}",
        f"w = {continuation_source['bounds']['w']}",
        f"h = {continuation_source['bounds']['h']}",
    ]

    for act_key, bounds in RECOVERY_BOUNDS.items():
        lines += [
            "",
            "[[recovery]]",
            f"act_key = {toml_string(act_key)}",
            f"x = {bounds['x']}",
            f"y = {bounds['y']}",
            f"w = {bounds['w']}",
            f"h = {bounds['h']}",
        ]

    for act_key, seats in TESTIMONY.items():
        for seat, reported in seats.items():
            lines += [
                "",
                "[[testimony]]",
                f"act_key = {toml_string(act_key)}",
                f"seat = {toml_string(seat)}",
                f"reported = {toml_string(reported)}",
            ]

    lines += [
        "",
        "# The happy scenario establishes both acts. The review scenario recovers act",
        "# a1 once -- act identity stable, region and attempt identities changing -- and",
        "# holds act a2, which therefore reaches no Archetypus at all.",
        "",
        "[[scenario]]",
        'name = "happy"',
        "recover_acts = []",
        "hold_acts = []",
        "",
        "[[scenario]]",
        'name = "review"',
        'recover_acts = ["a1"]',
        'hold_acts = ["a2"]',
        "",
        "# A seat whose attempt failed, exercising the witness `failed` state that Sol's",
        "# finding B-2 added to the closed vocabulary. It makes act a2 under-witnessed",
        "# without changing which acts are held.",
        "",
        "[[witness_failure]]",
        'scenario = "review"',
        'act_key = "a2"',
        'seat = "attestator_3"',
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    rendered = render_all()

    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    for ordinal, data in sorted(rendered.items()):
        (FIXTURE_DIR / f"page-{ordinal}.png").write_bytes(data)

    (PROOF_ROOT / "fixtures.toml").write_text(build_ingress_manifest(rendered), encoding="utf-8")
    (PROOF_ROOT / "skeleton_fixture.toml").write_text(
        build_skeleton_fixture(rendered), encoding="utf-8"
    )

    # Prove the crops the pipeline will take are actually derivable here, rather
    # than discovering it three stages downstream.
    for act in ACTS:
        source = act_descriptor(act["page_ordinal"], act["proposal_ordinal"])
        crop_png(rendered[act["page_ordinal"]], source["bounds"])

    print(f"wrote {len(rendered)} pages, fixtures.toml and skeleton_fixture.toml for {FIXTURE_ID}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
