def _with_entry(answer: dict, n: int, **fields) -> dict:
    """`answer` with entry `n`'s fields changed."""
    return {
        **answer,
        "acts": [{**entry, **fields} if entry["n"] == n else entry for entry in answer["acts"]],
    }


