def page_descriptor(ordinal):
    for page in ALL_PAGES:
        if page["ordinal"] == ordinal:
            return page
    raise ValueError(f"no page {ordinal}")


def act_descriptor(page_ordinal, proposal_ordinal):
    for act in page_descriptor(page_ordinal)["acts"]:
        if act["ordinal"] == proposal_ordinal:
            return act
    raise ValueError(f"no act {proposal_ordinal} on page {page_ordinal}")


def render_all() -> dict[int, bytes]:
    return {page["ordinal"]: render_page(page) for page in ALL_PAGES}


def toml_string(value: str) -> str:
    """One TOML basic string, with the control characters TOML forbids escaped.

    A basic string may not carry a literal newline, carriage return or tab, and
    a declared full-page witness response is the first fixture value that
    contains one -- a page reading is several lines by definition. Emitting the
    raw byte produced a file `tomllib` refuses, which is loud; emitting it
    without the escape into a multi-line form would have been worse, because the
    string the stage read back would no longer be the string declared here.
    """
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def toml_value(value) -> str:
    """The small JSON-native subset the synthetic Testimonium fixture needs."""
    if isinstance(value, str):
        return toml_string(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        if not all(isinstance(key, str) for key in value):
            raise ValueError("fixture TOML object keys must be strings")
        if unsafe := [key for key in value if _BARE_TOML_KEY.fullmatch(key) is None]:
            raise ValueError(f"fixture TOML object keys must be bare-safe: {unsafe!r}")
        fields = ", ".join(f"{key} = {toml_value(item)}" for key, item in sorted(value.items()))
        return "{ " + fields + " }"
    raise ValueError(f"fixture cannot render TOML value {value!r}")


def build_ingress_manifest(rendered: dict[int, bytes]) -> str:
    lines = [
        "version = 1",
        "",
        "# A public-safe proof image is added as an exact [[fixture]] entry carrying:",
        "# path, sha256, bytes, media_type, source, and reason. The ingress check accepts",
        "# JPEG, PNG, and TIFF only when all six fields match the staged image exactly.",
        "",
        "# These are generated by proof/build_fixture.py from proof/synthetic_pages.py.",
        "# They contain no register material of any kind: they are abstract synthetic",
        "# marks, drawn by a few dozen lines of zlib and struct, and they are the only",
        "# input the walking skeleton has.",
    ]
    import hashlib

    for ordinal in sorted(rendered):
        data = rendered[ordinal]
        lines += [
            "",
            "[[fixture]]",
            f'path = "proof/fixtures/{FIXTURE_ID}/page-{ordinal}.png"',
            f'sha256 = "{hashlib.sha256(data).hexdigest()}"',
            f"bytes = {len(data)}",
            'media_type = "image/png"',
            f'source = "generated by proof/build_fixture.py, fixture {FIXTURE_ID}"',
            'reason = "synthetic walking-skeleton input; public-safe by construction"',
        ]
    return "\n".join(lines) + "\n"


