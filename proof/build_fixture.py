def page_descriptor(ordinal):
    for page in ALL_PAGES:
        if page["ordinal"] == ordinal:
            return page
    raise ValueError(f"no page {ordinal}")


def act_descriptor(page_ordinal, proposal_ordinal):
    for act in page_descriptor(page_ordinal)["acts"]:
        if act["ordinal"] == proposal_ordinal:
            return act
    raise ValueError(f"no act {proposal_ordinal} on page {page_ordinal}")


def render_all() -> dict[int, bytes]:
    return {page["ordinal"]: render_page(page) for page in ALL_PAGES}


def toml_string(value: str) -> str:
    """Encode a TOML basic string without changing its Unicode text."""
    # JSON escapes C0 controls; TOML also forbids a literal U+007F.
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007F")


def toml_value(value) -> str:
    """The small JSON-native subset the synthetic Testimonium fixture needs."""
    if isinstance(value, str):
        return toml_string(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        if not all(isinstance(key, str) for key in value):
            raise ValueError("fixture TOML object keys must be strings")
        if unsafe := [key for key in value if _BARE_TOML_KEY.fullmatch(key) is None]:
            raise ValueError(f"fixture TOML object keys must be bare-safe: {unsafe!r}")
        fields = ", ".join(f"{key} = {toml_value(item)}" for key, item in sorted(value.items()))
        return "{ " + fields + " }"
    raise ValueError(f"fixture cannot render TOML value {value!r}")


def build_ingress_manifest(rendered: dict[int, bytes]) -> str:
    lines = [
        "version = 1",
        "",
        "# A public-safe proof image is added as an exact [[fixture]] entry carrying:",
        "# path, sha256, bytes, media_type, source, and reason. The ingress check accepts",
        "# JPEG, PNG, and TIFF only when all six fields match the staged image exactly.",
        "",
        "# These are generated by proof/build_fixture.py from proof/synthetic_pages.py.",
        "# They contain no register material of any kind: they are abstract synthetic",
        "# marks, drawn by a few dozen lines of zlib and struct, and they are the only",
        "# input the walking skeleton has.",
    ]
    import hashlib

    for ordinal in sorted(rendered):
        data = rendered[ordinal]
        lines += [
            "",
            "[[fixture]]",
            f'path = "proof/fixtures/{FIXTURE_ID}/page-{ordinal}.png"',
            f'sha256 = "{hashlib.sha256(data).hexdigest()}"',
            f"bytes = {len(data)}",
            'media_type = "image/png"',
            f'source = "generated by proof/build_fixture.py, fixture {FIXTURE_ID}"',
            'reason = "synthetic walking-skeleton input; public-safe by construction"',
        ]
    return "\n".join(lines) + "\n"


def build_skeleton_fixture(rendered: dict[int, bytes]) -> str:
    import hashlib

    lines = [
        "# The pipeline's declaration of the synthetic fixture.",
        "#",
        "# Read as data by every stage program, never imported: stages exchange",
        "# artifacts on disk and import only common/, so a fixture that arrived as",
        "# Python would be a stage coupling itself to another package through a side",
        "# door. Generated by proof/build_fixture.py -- edit that, not this.",
        "",
        f"fixture_id = {toml_string(FIXTURE_ID)}",
        "# Model chairs, witness floor, and serving recipes are owned by",
        "# config/models.toml. This fixture contains only synthetic fixture data.",
    ]

    for ordinal in sorted(rendered):
        page = page_descriptor(ordinal)
        data = rendered[ordinal]
        lines += [
            "",
            "[[page]]",
            f"ordinal = {ordinal}",
            f'path = "fixtures/{FIXTURE_ID}/page-{ordinal}.png"',
            f'sha256 = "{hashlib.sha256(data).hexdigest()}"',
            f"width = {page['width']}",
            f"height = {page['height']}",
        ]
        if scenarios := page.get("scenarios"):
            lines.append("scenarios = [" + ", ".join(toml_string(item) for item in scenarios) + "]")

    for act in ACTS:
        source = act_descriptor(act["page_ordinal"], act["proposal_ordinal"])
        bounds = source["bounds"]
        lines += [
            "",
            "[[act]]",
            f"key = {toml_string(act['key'])}",
            f"page_ordinal = {act['page_ordinal']}",
            f"proposal_ordinal = {act['proposal_ordinal']}",
            f"x = {bounds['x']}",
            f"y = {bounds['y']}",
            f"w = {bounds['w']}",
            f"h = {bounds['h']}",
            f"text = {toml_string(act['text'])}",
        ]

    for observation in NATIVE_OBSERVATIONS:
        lines += ["", "[[native_observation]]"]
        for key in ("scenario", "chair", "page_ordinal", "x", "y", "w", "h"):
            if key not in observation:
                continue
            value = observation[key]
            lines.append(f"{key} = {toml_string(value) if isinstance(value, str) else value}")

    for row in SURYA_LINES:
        lines += ["", "[[surya_line]]"]
        lines += [f"{key} = {toml_value(value)}" for key, value in row.items()]

    for row in SURYA_BLOCKS:
        lines += ["", "[[surya_block]]"]
        lines += [f"{key} = {toml_value(value)}" for key, value in row.items()]

    # a2 continues across the page break: a region of the same act, not a new act.
    continuation_source = act_descriptor(2, 1)
    lines += [
        "",
        "[[continuation]]",
        'act_key = "a2"',
        "page_ordinal = 2",
        f"x = {continuation_source['bounds']['x']}",
        f"y = {continuation_source['bounds']['y']}",
        f"w = {continuation_source['bounds']['w']}",
        f"h = {continuation_source['bounds']['h']}",
    ]

    for row in PAGE_TESTIMONY:
        lines += ["", "[[testimony]]"]
        lines += [
            f"{key} = {toml_value(row[key])}"
            for key in (
                "scenario",
                "page_ordinal",
                "chair",
                "payload",
                "raw_responses",
                "witness_reported",
                "format_capabilities",
            )
            if key in row
        ]

    for row in CHURRO_PAGE_RESPONSES:
        lines += [
            "",
            "[[churro_page_response]]",
            *([f"scenario = {toml_string(row['scenario'])}"] if "scenario" in row else []),
            f"page_ordinal = {row['page_ordinal']}",
            f"chair = {toml_string(row['chair'])}",
            f"raw_xml = {toml_string(row['raw_xml'])}",
            f"transport_stop_reason = {toml_string(row['transport_stop_reason'])}",
        ]

    for row in DETECTOR_RECORDS:
        lines += [
            "",
            "[[detector_record]]",
            *([f"scenario = {toml_string(row['scenario'])}"] if "scenario" in row else []),
            f"page_ordinal = {row['page_ordinal']}",
            f"corners = {toml_value(row['corners'])}",
            f"score_bp = {row['score_bp']}",
        ]

    for row in DAI_RECORD_RESPONSES:
        lines += [
            "",
            "[[dai_record_response]]",
            *([f"scenario = {toml_string(row['scenario'])}"] if "scenario" in row else []),
            f"page_ordinal = {row['page_ordinal']}",
            f"detector_ordinal = {row['detector_ordinal']}",
            f"chair = {toml_string(row['chair'])}",
            f"text = {toml_string(row['text'])}",
        ]

    for name, departure in SCENARIOS:
        lines += [""]
        if departure is not None:
            lines += [f"# {name}: {departure}"]
        lines += ["[[scenario]]", f"name = {toml_string(name)}"]
    lines += [
        "",
        "# The fake Perlector's answer to a whole-page reading, one per scenario and page.",
        "# `answer` is the reply text exactly.",
        "",
    ]
    for row in PAGE_ANSWERS:
        lines += [
            "[[page_answer]]",
            f"scenario = {toml_string(row['scenario'])}",
            f"page_ordinal = {row['page_ordinal']}",
            "answer = "
            + toml_string(
                row["answer"]
                if isinstance(row["answer"], str)
                else json.dumps(row["answer"], separators=(",", ":"))
            ),
            "",
        ]
    for table, rows in (
        ("witness_empty", WITNESS_EMPTY),
        ("witness_not_run", WITNESS_NOT_RUN),
        ("witness_malformed", WITNESS_MALFORMED),
    ):
        for row in rows:
            lines += ["", f"[[{table}]]"]
            lines += [f"{key} = {toml_value(value)}" for key, value in row.items()]

    for row in STRUCTURE_FAILURES:
        lines += [
            "",
            "# A recorded structure-chair failure: the Designator holds the page and every",
            "# act that needed it, with the reason named, rather than skipping either.",
            "",
            "[[structure_failure]]",
            f"scenario = {toml_string(row['scenario'])}",
            f"page_ordinal = {row['page_ordinal']}",
            f"reason_code = {toml_string(row['reason_code'])}",
        ]

    lines += [
        "",
        "# Per-scenario declared digests the checked-in bytes cannot match, so the",
        "# door refuses those pages through its real inspection path. The declared",
        "# digest is all zeros: unmistakably not the digest of anything here.",
    ]
    for refusal in PAGE_REFUSALS:
        lines += [
            "",
            "[[page_refusal]]",
            f"scenario = {toml_string(refusal['scenario'])}",
            f"ordinal = {refusal['ordinal']}",
            f"declared_sha256 = {toml_string(_UNMATCHABLE_SHA256)}",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    rendered = render_all()

    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    for ordinal, data in sorted(rendered.items()):
        (FIXTURE_DIR / f"page-{ordinal}.png").write_bytes(data)

    (PROOF_ROOT / "fixtures.toml").write_text(build_ingress_manifest(rendered), encoding="utf-8")
    (PROOF_ROOT / "skeleton_fixture.toml").write_text(
        build_skeleton_fixture(rendered), encoding="utf-8"
    )

    # Fail here if a crop the pipeline will take is not derivable.
    for act in ACTS:
        source = act_descriptor(act["page_ordinal"], act["proposal_ordinal"])
        crop_png(rendered[act["page_ordinal"]], source["bounds"])

    print(f"wrote {len(rendered)} pages, fixtures.toml and skeleton_fixture.toml for {FIXTURE_ID}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
