"""Render the declared proof pages and write both declarations that describe them.

Run from the repository root:

    python3 proof/build_fixture.py

It writes three things and nothing else:

  proof/fixtures/<fixture-id>/page-N.png   the checked-in bytes themselves
  proof/fixtures.toml                      the ingress declaration the hook enforces
  proof/skeleton_fixture.toml              the pipeline's declaration of what is on them

**The checked-in bytes are the authority, not this script.** Spec 01 asks for fixed
checked-in bytes with expected digests precisely so that encoders, fonts and
metadata cannot vary across machines — and zlib's exact output, while a pure
function of its input for a given implementation, is not guaranteed identical
across zlib builds. So a machine whose regenerated bytes differ has not found a
defect in the fixture; it has found a different zlib. The test beside this script
asserts what actually matters and holds everywhere: the checked-in files decode to
exactly the pixels this generator describes.

Two declarations rather than one because they answer different questions and are
read by different things. `fixtures.toml` answers "may these bytes be in git?" and
is enforced by the ingress hook on every commit and push. `skeleton_fixture.toml`
answers "what is on these pages, and what should the fakes do?" and is read by the
stage programs as data.
"""

